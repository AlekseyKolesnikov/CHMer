/* WebHelp runtime: adds the header and the Contents / Index / Search sidebar around a topic.
   window.WEBHELP comes from data.js and window.WEBHELP_SEARCH from search.js (loaded when
   searching); both are generated by build_webhelp.py. They are loaded with <script> tags
   because the help runs from file://, where browsers block fetch(). */
(function () {
  'use strict';

  const H = window.WEBHELP;
  if (!H || !document.body) return;

  const assetBase = (document.currentScript && document.currentScript.src || '').replace(/[^/]*$/, '');
  const rootBase = assetBase.replace(/[^/]*\/$/, '');
  const root = document.documentElement;
  const params = new URLSearchParams(location.search);
  const page = keyOf(location.href);
  const KEY = 'wh:' + H.title + ':';

  // sessionStorage keeps the sidebar state between pages; Firefox gives every file:// page
  // its own storage, so there it simply starts fresh on each page
  const session = storage(function () { return window.sessionStorage; });
  const local = storage(function () { return window.localStorage; });

  function storage(get) {
    let s = null;
    try { s = get(); s.getItem(KEY); } catch (e) { s = null; }
    return {
      get: function (k) { try { return s ? s.getItem(KEY + k) : null; } catch (e) { return null; } },
      set: function (k, v) { try { if (s) s.setItem(KEY + k, v); } catch (e) { /* storage unavailable */ } }
    };
  }

  // Paths in the data are relative to the help root; topics may sit in subfolders
  function hrefOf(u) {
    const i = u.indexOf('#');
    return rootBase + encodeURI(i < 0 ? u : u.slice(0, i)) + (i < 0 ? '' : u.slice(i));
  }

  // A page is identified by its full path, ignoring case as Windows does
  function keyOf(url) {
    try { return decode(new URL(url, location.href).pathname).toLowerCase(); } catch (e) { return ''; }
  }

  function decode(s) {
    try { return decodeURIComponent(s); } catch (e) { return s; }
  }

  function el(tag, props, children) {
    const e = document.createElement(tag);
    for (const k in props || {}) {
      if (k === 'class') e.className = props[k];
      else if (k === 'text') e.textContent = props[k];
      else if (k.startsWith('on')) e.addEventListener(k.slice(2), props[k]);
      else e.setAttribute(k, props[k]);
    }
    for (const c of children || []) if (c) e.append(c);
    return e;
  }

  // Search terms: words, or "quoted phrases"
  function termsOf(query) {
    const terms = [];
    for (const m of query.toLowerCase().matchAll(/"([^"]+)"|(\S+)/g)) {
      const t = (m[1] || m[2]).trim();
      if (t.length > 1 && !terms.includes(t)) terms.push(t);
    }
    return terms;
  }

  function termRegex(terms) {
    return new RegExp(terms.map(function (t) { return t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }).join('|'), 'gi');
  }

  function appendMarked(parent, text, re, cls) {
    let last = 0;
    for (const m of text.matchAll(re)) {
      if (m.index > last) parent.append(text.slice(last, m.index));
      parent.append(el('mark', { class: cls || '', text: m[0] }));
      last = m.index + m[0].length;
    }
    if (last < text.length) parent.append(text.slice(last));
  }

  // Highlight the terms of the search that led here (?hl=...), before the frame is added
  const highlight = params.get('hl') || '';
  let firstMark = null;
  if (highlight && termsOf(highlight).length) {
    const re = termRegex(termsOf(highlight));
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (n.parentElement.closest('script, style')) return NodeFilter.FILTER_REJECT;
        re.lastIndex = 0;
        return re.test(n.data) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
      }
    });
    const found = [];
    while (walker.nextNode()) found.push(walker.currentNode);
    for (const n of found) {
      const span = document.createDocumentFragment();
      appendMarked(span, n.data, re, 'wh-hl');
      n.replaceWith(span);
    }
    firstMark = document.querySelector('mark.wh-hl');
  }

  // Contents tree: number the nodes and find the one for this page
  const nodes = [];
  (function walk(list, parent) {
    for (const n of list) {
      n.id = nodes.length;
      n.parent = parent;
      if (n.u) n.k = keyOf(hrefOf(n.u));
      nodes.push(n);
      if (n.c) walk(n.c, n);
    }
  })(H.toc, null);

  const anchor = decode(location.hash.slice(1));
  const current = nodes.find(function (n) { return n.k === page && (n.u.split('#')[1] || '') === anchor; })
    || nodes.find(function (n) { return n.k === page; });

  const open = new Set((session.get('toc') || '').split(',').filter(Boolean).map(Number));
  for (let p = current && current.parent; p; p = p.parent) open.add(p.id);

  // Browse sequence for Previous / Next: the contents in order, each topic once
  const sequence = [];
  const seen = new Set();
  for (const n of nodes) {
    if (n.k && !seen.has(n.k)) {
      seen.add(n.k);
      sequence.push(n);
    }
  }
  const at = sequence.findIndex(function (n) { return n.k === page; });

  if (document.title.indexOf(H.title) < 0) document.title = (document.title ? document.title + ' - ' : '') + H.title;

  // Header
  const toggle = el('button', { class: 'wh-toggle', type: 'button', title: 'Show or hide the sidebar', 'aria-label': 'Sidebar' });
  const header = el('header', { id: 'wh-header' }, [
    toggle,
    el('a', { class: 'wh-title', href: hrefOf(H.home), text: H.title }),
    el('span', { class: 'wh-spacer' }),
    at >= 0 ? navLink(sequence[at - 1], 'wh-prev', 'Previous') : null,
    at >= 0 ? navLink(sequence[at + 1], 'wh-next', 'Next') : null,
    el('span', { class: 'wh-links' }, H.links.map(function (l) { return el('a', { href: hrefOf(l.u), text: l.t }); }))
  ]);

  function navLink(node, cls, text) {
    return node
      ? el('a', { class: 'wh-nav ' + cls, href: hrefOf(node.u), title: node.t, text: text })
      : el('span', { class: 'wh-nav ' + cls + ' wh-disabled', text: text });
  }

  // Sidebar
  const tocPanel = el('div', { class: 'wh-panel wh-toc', id: 'wh-panel-toc', role: 'tabpanel' }, [tocList(H.toc)]);
  const indexFilter = el('input', { type: 'search', placeholder: 'Type a keyword', 'aria-label': 'Filter the index' });
  const indexList = el('div');
  const indexPanel = el('div', { class: 'wh-panel', id: 'wh-panel-index', role: 'tabpanel' }, [
    el('div', { class: 'wh-field' }, [indexFilter]), indexList
  ]);
  const searchInput = el('input', { type: 'search', placeholder: 'Search the help', 'aria-label': 'Search the help' });
  const searchResults = el('div');
  const searchPanel = el('div', { class: 'wh-panel', id: 'wh-panel-search', role: 'tabpanel' }, [
    el('div', { class: 'wh-field' }, [searchInput]), searchResults
  ]);
  const tabs = [
    { id: 'toc', text: 'Contents', panel: tocPanel },
    { id: 'index', text: 'Index', panel: indexPanel, input: indexFilter },
    { id: 'search', text: 'Search', panel: searchPanel, input: searchInput }
  ];
  for (const t of tabs) {
    t.button = el('button', { type: 'button', role: 'tab', 'aria-controls': t.panel.id, text: t.text,
      onclick: function () { selectTab(t.id, true); } });
  }
  const side = el('nav', { id: 'wh-side', 'aria-label': 'Help navigation' }, [
    el('div', { class: 'wh-tabs', role: 'tablist' }, tabs.map(function (t) { return t.button; }))
  ].concat(tabs.map(function (t) { return t.panel; })));

  function tocList(list) {
    const ul = el('ul');
    for (const n of list) {
      const li = el('li', n.c && open.has(n.id) ? { class: 'wh-open' } : null);
      const row = el('div', { class: 'wh-row' });
      if (n.c) {
        const twisty = el('button', { class: 'wh-twisty', type: 'button', 'aria-label': 'Expand ' + n.t,
          'aria-expanded': String(open.has(n.id)) });
        twisty.addEventListener('click', function () { toggleNode(n, li, twisty); });
        row.append(twisty);
      } else {
        row.append(el('span', { class: 'wh-twisty' }));
      }
      const label = n.u ? el('a', { href: hrefOf(n.u), text: n.t }) : el('span', { class: 'wh-book', text: n.t });
      if (!n.u && n.c) label.addEventListener('click', function () { toggleNode(n, li, row.firstChild); });
      if (n === current) {
        label.classList.add('wh-current');
        label.setAttribute('aria-current', 'page');
      }
      row.append(label);
      li.append(row);
      if (n.c) li.append(tocList(n.c));
      ul.append(li);
    }
    return ul;
  }

  function toggleNode(n, li, twisty) {
    const isOpen = li.classList.toggle('wh-open');
    twisty.setAttribute('aria-expanded', String(isOpen));
    if (isOpen) open.add(n.id); else open.delete(n.id);
    session.set('toc', Array.from(open).join(','));
  }

  // Index
  let indexShown = null;
  function renderIndex() {
    const filter = indexFilter.value.trim().toLowerCase();
    if (filter === indexShown) return;
    indexShown = filter;
    session.set('filter', indexFilter.value);
    const ul = el('ul', { class: 'wh-index' });
    for (const e of H.index) {
      if (filter && e.k.toLowerCase().indexOf(filter) < 0) continue;
      if (e.r.length === 1) {
        ul.append(el('li', null, [el('a', { href: hrefOf(e.r[0].u), title: e.r[0].t, text: e.k })]));
      } else {
        ul.append(el('li', null, [
          el('span', { text: e.k }),
          el('ul', null, e.r.map(function (r) { return el('li', null, [el('a', { href: hrefOf(r.u), text: r.t || r.u })]); }))
        ]));
      }
    }
    indexList.replaceChildren(ul.firstChild ? ul : el('p', { class: 'wh-empty', text: 'No matching keywords.' }));
  }
  indexFilter.value = session.get('filter') || '';
  indexFilter.addEventListener('input', renderIndex);

  // Search
  let docs = null;
  let searchTimer = 0;

  function loadSearch(done) {
    if (docs) return done();
    if (!window.WEBHELP_SEARCH) {
      document.head.append(el('script', { src: assetBase + 'search.js',
        onload: function () { loadSearch(done); },
        onerror: function () { searchResults.replaceChildren(el('p', { class: 'wh-empty', text: 'The search index is missing.' })); } }));
      return;
    }
    docs = window.WEBHELP_SEARCH.map(function (d) {
      return { u: d.u, t: d.t, x: d.x, lt: d.t.toLowerCase(), lx: d.x.toLowerCase() };
    });
    done();
  }

  function count(text, term) {
    let n = 0;
    for (let i = text.indexOf(term); i >= 0 && n < 100; i = text.indexOf(term, i + term.length)) n++;
    return n;
  }

  function runSearch() {
    const query = searchInput.value;
    session.set('query', query);
    const terms = termsOf(query);
    if (!terms.length) {
      searchResults.replaceChildren(el('p', { class: 'wh-empty', text: 'Type words to find; use "quotes" for a phrase.' }));
      return;
    }
    loadSearch(function () {
      if (searchInput.value !== query) return;
      const hits = [];
      for (const d of docs) {
        let score = 0;
        for (const t of terms) {
          const inTitle = d.lt.indexOf(t) >= 0;
          const n = count(d.lx, t);
          if (!inTitle && !n) { score = 0; break; }
          score += (inTitle ? 100 : 0) + Math.min(n, 25);
        }
        if (score) hits.push({ d: d, score: score });
      }
      hits.sort(function (a, b) { return b.score - a.score || a.d.t.localeCompare(b.d.t); });
      const re = termRegex(terms);
      const list = el('ol', { class: 'wh-results' });
      for (const h of hits) {
        const title = el('a', { href: hrefOf(h.d.u) + '?hl=' + encodeURIComponent(query) });
        appendMarked(title, h.d.t, re);
        if (keyOf(hrefOf(h.d.u)) === page) title.classList.add('wh-current');
        const snip = el('p');
        appendMarked(snip, snippet(h.d, terms), re);
        list.append(el('li', null, [title, snip]));
      }
      searchResults.replaceChildren(
        el('p', { class: 'wh-count', text: hits.length ? hits.length + (hits.length === 1 ? ' topic' : ' topics') : 'Nothing found.' }),
        list);
    });
  }

  function snippet(d, terms) {
    let pos = -1;
    for (const t of terms) {
      const i = d.lx.indexOf(t);
      if (i >= 0 && (pos < 0 || i < pos)) pos = i;
    }
    if (pos < 0) pos = 0;
    let start = Math.max(0, pos - 60);
    let end = Math.min(d.x.length, pos + 160);
    if (start > 0) { const s = d.x.indexOf(' ', start); if (s >= 0 && s < pos) start = s + 1; }
    if (end < d.x.length) { const e = d.x.lastIndexOf(' ', end); if (e > pos) end = e; }
    // An escaped ellipsis, because topics in an ANSI code page load this file in their encoding
    return (start > 0 ? '\u2026 ' : '') + d.x.slice(start, end) + (end < d.x.length ? ' \u2026' : '');
  }

  searchInput.value = highlight || session.get('query') || '';
  searchInput.addEventListener('input', function () {
    clearTimeout(searchTimer);
    searchTimer = setTimeout(runSearch, 200);
  });
  searchInput.addEventListener('keydown', function (e) {
    if (e.key === 'Enter') { clearTimeout(searchTimer); runSearch(); }
  });

  // Tabs
  let activeTab = null;
  function selectTab(id, focus) {
    activeTab = id;
    for (const t of tabs) {
      const on = t.id === id;
      t.button.setAttribute('aria-selected', String(on));
      t.panel.hidden = !on;
      if (on && focus && t.input) t.input.focus();
    }
    session.set('tab', id);
    if (id === 'index') renderIndex();
    if (id === 'search') runSearch();
  }

  // Sidebar visibility: remembered on wide windows, closed by default on narrow ones
  const narrow = window.matchMedia('(max-width: 800px)');
  function showSide(show) {
    root.classList.toggle('wh-side-hidden', !show);
    toggle.setAttribute('aria-expanded', String(show));
  }
  toggle.addEventListener('click', function () {
    const show = root.classList.contains('wh-side-hidden');
    showSide(show);
    if (!narrow.matches) local.set('side', show ? '1' : '0');
  });
  narrow.addEventListener('change', function () { showSide(!narrow.matches && local.get('side') !== '0'); });
  showSide(!narrow.matches && local.get('side') !== '0');

  document.body.prepend(header, side);
  const stored = session.get('tab');
  selectTab(highlight ? 'search' : tabs.some(function (t) { return t.id === stored; }) ? stored : 'toc', false);

  // Keep the sidebar where it was, then make sure this page's entry is visible
  const scroll = (session.get('scroll') || '').split(':');
  if (scroll[0] === activeTab) {
    const panel = tabs.find(function (t) { return t.id === activeTab; }).panel;
    panel.scrollTop = Number(scroll[1]) || 0;
  }
  const mark = activeTab === 'toc' && tocPanel.querySelector('.wh-current');
  if (mark) {
    const r = mark.getBoundingClientRect();
    const p = tocPanel.getBoundingClientRect();
    if (r.top < p.top || r.bottom > p.bottom) tocPanel.scrollTop += r.top - p.top - p.height / 2;
  }
  window.addEventListener('pagehide', function () {
    const panel = tabs.find(function (t) { return t.id === activeTab; }).panel;
    session.set('scroll', activeTab + ':' + Math.round(panel.scrollTop));
  });

  if (firstMark && !location.hash) firstMark.scrollIntoView({ block: 'center' });
})();
